"""
Houses all the logic for generating motifs during model training.
"""

import numpy as np
from biotite.structure import AtomArray

from protenix.data.motif_utils import get_chain_motif, get_ligand_motif


class MotifMaker:
    """
    Main class for generating motifs during model training. Delegates which motif generation
    method is most suitable for the task. The different motif selection methods are as follows:

    - get_ligand_motif:
        Generates a motif centered around a ligand. If the complex contains a ligand, this method is
        picked with probability `ligand_motif_prob`. Otherwise, get_chain_motif is used.
        The whole ligand is used included in the motif with probability `whole_ligand_prob`, otherwise
        a BFS is performed to pick a contiguous subset of the ligand. The surrounding motif is then
        generated using the generate_motif_around_a_point function.

    - get_chain_motif:
        Generates a motif centered around a pocket-esque point on a polymer chain. A polymer chain
        from the complex is picked uniformly at random. A pocket score is calculated for each atom in
        the chain which is the distance between the atom and the centroid of its nearest 25 neighbours.
        A seed atom is picked uniformly at random from the atoms with a pocket score less than
        `pocket_score_threshold`. The surrounding motif is then generated using the
        generate_motif_around_a_point function.

    - generate_motif_around_a_point:
        Generates a motif centered around a point. The residues lying within search radius, picked uniformly
         at random from the interval [r_min, r_max], are identified. Each residues is included in the motif
         according to `residue_inclusion_probability`. With probability `whole_sidechain_prob`, the whole-sidechain
         atoms are added to the motif. Otherwise, a partial residue motif is generated using get_partial_residue_motif.

    - get_partial_residue_motif:
        Generates a partial residue motif. With probability `sidechain_seed_is_tip_prob`, the tip atom is picked to be
        the seed atom. Otherwise, a seed atom is picked uniformly at random from the residue. A connected subgraph of
        the sidechain is then generated by extending outward from the seed atom by n_bonds ~ Geo(p) where
        p = `sidechain_bfs_depth_prob`.
    """

    def __init__(
        self,
        ligand_motif_prob: float = 0.8,
        whole_ligand_prob: float = 0.7,
        whole_sidechain_prob: float = 0.2,
        pocket_score_threshold: float = 0.18,
        pocket_n_neighbours: int = 25,
        sidechain_seed_is_tip_prob: float = 0.8,
        sidechain_bfs_depth_prob: float = 0.5,
        residue_inclusion_prob: float = 0.9,
        r_min: float = 3.0,
        r_max: float = 6.0,
    ):
        """
        Args:
            ligand_motif_prob: Probability get_ligand_motif is used to generate motif for ligand complexes.
            whole_ligand_prob: Probability get_ligand_motif uses the whole ligand in the motif.
            whole_sidechain_prob: Probability generate_motif_around_a_point uses the whole sidechain in the motif.
            pocket_score_threshold: Threshold for pocket score to identify seed atom for get_chain_motif.
            pocket_n_neighbours: Number of neighbours to consider for pocket score for get_chain_motif.
            sidechain_seed_is_tip_prob: Probability generate_motif_around_a_point uses the tip atom as the seed atom.
            sidechain_bfs_depth_prob: Probability of the number of bonds to extend out from the seed atom for get_partial_residue_motif.
            residue_inclusion_probability: Probability of including a residue in the motif if lies in search sphere.
            r_min: Minimum radius in angstroms for sphere search.
            r_max: Maximum radius in angstroms for sphere search.
        """
        self.ligand_motif_prob = ligand_motif_prob
        self.whole_ligand_prob = whole_ligand_prob
        self.whole_sidechain_prob = whole_sidechain_prob
        self.pocket_score_threshold = pocket_score_threshold
        self.pocket_n_neighbours = pocket_n_neighbours
        self.sidechain_seed_is_tip_prob = sidechain_seed_is_tip_prob
        self.sidechain_bfs_depth_prob = sidechain_bfs_depth_prob
        self.residue_inclusion_prob = residue_inclusion_prob
        self.r_min = r_min
        self.r_max = r_max

    def make_motif(self, atom_array: AtomArray) -> AtomArray:
        """
        Makes the motif for the given atom and token arrays. This is the main function generating
        the motif. It returns the motif atom array rather than changing the original atom array.
        """
        if atom_array.is_ligand.any() and np.random.rand() < self.ligand_motif_prob:
            motif_atom_array = get_ligand_motif(
                atom_array,
                whole_ligand_prob=self.whole_ligand_prob,
                r_min=self.r_min,
                r_max=self.r_max,
                residue_inclusion_probability=self.residue_inclusion_prob,
                whole_sidechain_probability=self.whole_sidechain_prob,
            )
        else:
            motif_atom_array = get_chain_motif(
                atom_array,
                r_min=self.r_min,
                r_max=self.r_max,
                pocket_score_threshold=self.pocket_score_threshold,
                residue_inclusion_probability=self.residue_inclusion_prob,
                whole_sidechain_probability=self.whole_sidechain_prob,
            )

        return motif_atom_array

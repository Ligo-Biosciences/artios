"""
Houses all the logic for generating motifs during model training.
"""

from logging import getLogger

import networkx as nx
import numpy as np
from biotite.structure import AtomArray

from protenix.data.motif_utils import (
    bfs_nodes_by_count,
    compute_pocket_scores,
    get_seed_atom_from_array,
)

logger = getLogger(__name__)


class MotifMaker:
    """
    Main class for generating motifs during model training. Delegates which motif generation
    method is most suitable for the task. The different motif selection methods are as follows:

    - _generate_ligand_motif:
        Generates a motif centered around a ligand. If the complex contains a ligand, this method is
        picked with probability `ligand_motif_prob`. Otherwise, _generate_chain_motif is used.
        The whole ligand is used included in the motif with probability `whole_ligand_prob`, otherwise
        a BFS is performed to pick a contiguous subset of the ligand. The surrounding motif is then
        generated using the _generate_motif_around_point function.

    - _generate_chain_motif:
        Generates a motif centered around a pocket-esque point on a polymer chain. A polymer chain
        from the complex is picked uniformly at random. A pocket score is calculated for each atom in
        the chain which is the distance between the atom and the centroid of its nearest 25 neighbours.
        A seed atom is picked uniformly at random from the atoms with a pocket score less than
        `pocket_score_threshold`. The surrounding motif is then generated using the
        _generate_motif_around_point function.

    - _generate_motif_around_point:
        Generates a motif centered around a point. The residues lying within search radius, picked uniformly
         at random from the interval [r_min, r_max], are identified. Each residues is included in the motif
         according to `residue_inclusion_probability`. With probability `whole_sidechain_prob`, the whole-sidechain
         atoms are added to the motif. Otherwise, a partial residue motif is generated using _get_partial_residue_motif.

    - _get_partial_residue_motif:
        Generates a partial residue motif. With probability `sidechain_seed_is_tip_prob`, the tip atom is picked to be
        the seed atom. Otherwise, a seed atom is picked uniformly at random from the residue. A connected subgraph of
        the sidechain is then generated by extending outward from the seed atom by n_bonds ~ Geo(p) where
        p = `sidechain_bfs_depth_prob`.
    """

    def __init__(
        self,
        ligand_motif_prob: float = 0.8,
        whole_ligand_prob: float = 0.7,
        whole_sidechain_prob: float = 0.2,
        pocket_score_threshold: float = 0.18,
        pocket_n_neighbours: int = 25,
        sidechain_seed_is_tip_prob: float = 0.8,
        sidechain_bfs_depth_prob: float = 0.5,
        residue_inclusion_prob: float = 0.9,
        r_min: float = 3.0,
        r_max: float = 6.0,
        motif_train_rate: float = 0.0,
        **kwargs,
    ):
        """
        Args:
            ligand_motif_prob (float): Probability _generate_ligand_motif is used to generate motif for ligand complexes.
            whole_ligand_prob (float): Probability _generate_ligand_motif uses the whole ligand in the motif.
            whole_sidechain_prob (float): Probability _generate_motif_around_point uses the whole sidechain in the motif.
            pocket_score_threshold (float): Threshold for pocket score to identify seed atom for _generate_chain_motif.
            pocket_n_neighbours (int): Number of neighbours to consider for pocket score for _generate_chain_motif.
            sidechain_seed_is_tip_prob (float): Probability _generate_motif_around_point uses the tip atom as the seed atom.
            sidechain_bfs_depth_prob (float): Probability of the number of bonds to extend out from the seed atom for _get_partial_residue_motif.
            residue_inclusion_prob (float): Probability of including a residue in the motif if lies in search sphere.
            r_min (float): Minimum radius in angstroms for sphere search.
            r_max (float): Maximum radius in angstroms for sphere search.
            motif_train_rate (float): Training rate for motif generation (used in dataset).
        """
        self.ligand_motif_prob = ligand_motif_prob
        self.whole_ligand_prob = whole_ligand_prob
        self.whole_sidechain_prob = whole_sidechain_prob
        self.pocket_score_threshold = pocket_score_threshold
        self.pocket_n_neighbours = pocket_n_neighbours
        self.sidechain_seed_is_tip_prob = sidechain_seed_is_tip_prob
        self.sidechain_bfs_depth_prob = sidechain_bfs_depth_prob
        self.residue_inclusion_prob = residue_inclusion_prob
        self.r_min = r_min
        self.r_max = r_max

    def make_motif(self, atom_array: AtomArray) -> AtomArray:
        """
        Makes the motif for the given atom array. This is the main public function generating
        the motif. It returns the motif atom array rather than changing the original atom array.

        Args:
            atom_array (AtomArray): Input Biotite AtomArray

        Returns:
            AtomArray: Motif atom array extracted from the input
        """
        if atom_array.is_ligand.any() and np.random.rand() < self.ligand_motif_prob:
            motif = self._generate_ligand_motif(atom_array)
        else:
            motif = self._generate_chain_motif(atom_array)

        num_residues_in_motif = len(np.unique(motif.res_id))
        if num_residues_in_motif > 20:
            logger.warning(
                f"Motif has too many residues:{num_residues_in_motif} . Returning None for motif."
            )
            return None

        return motif

    def _generate_ligand_motif(self, atom_array: AtomArray) -> AtomArray:
        """
        Logic for picking a motif from a complex that contains a ligand.

        Args:
            atom_array (AtomArray): Input Biotite AtomArray

        Returns:
            AtomArray: Motif atom array centered around a ligand
        """
        motif_atom_array = AtomArray(0)

        ligand_mask = atom_array.chain_mol_type == "ligand"
        ligand_asym_ids = np.unique(atom_array.label_asym_id[ligand_mask])
        ligand_motif_asym_id = np.random.choice(ligand_asym_ids)
        ligand_array = atom_array[atom_array.label_asym_id == ligand_motif_asym_id]

        if np.random.rand() < self.whole_ligand_prob or len(ligand_array) == 1:
            # Add whole ligand to motif
            motif_atom_array += ligand_array
            motif_atom_array += self._generate_motif_around_point(
                point_coord=get_seed_atom_from_array(ligand_array),
                atom_array=atom_array,
            )
        else:
            # Add partial ligand to motif
            ligand_graph = ligand_array.bonds.as_graph()
            graph_nodes = list(ligand_graph.nodes())

            if len(graph_nodes) == 0:
                logger.warning(
                    f"No nodes in ligand graph, but {len(ligand_array)} atoms in array. Returning None for motif."
                )
                return None

            seed_ligand = np.random.choice(graph_nodes)

            ligand_proportion = np.random.rand()
            num_lig_atoms_in_motif = max(1, int(ligand_proportion * len(ligand_graph)))

            # Get nodes via BFS up to the target count
            nodes = bfs_nodes_by_count(
                ligand_graph, seed_ligand, num_lig_atoms_in_motif
            )
            ligand_motif_array = ligand_array[nodes]

            motif_atom_array += ligand_motif_array
            motif_atom_array += self._generate_motif_around_point(
                point_coord=get_seed_atom_from_array(ligand_motif_array),
                atom_array=atom_array,
            )

        return motif_atom_array

    def _generate_chain_motif(self, atom_array: AtomArray) -> AtomArray:
        """
        Generates a motif centered around a pocket-esque point on a polymer chain.
        Picks a single polymer chain from the complex, generates a motif and returns it.
        Will pick a residue 'inside' the polymer using pocket score heuristic.

        Args:
            atom_array (AtomArray): Input Biotite AtomArray

        Returns:
            AtomArray: Motif atom array centered around a chain pocket
        """
        # Filter for polymer chains
        atom_array = atom_array[
            np.isin(atom_array.chain_mol_type, ["protein", "RNA", "DNA"])
        ]
        if len(atom_array) == 0:
            logger.warning(
                "No polymer chains in the atom array. Returning None for motif."
            )
            return None

        # Pick a chain uniformly at random
        try:
            chain_id = np.random.choice(np.unique(atom_array.label_asym_id))
        except ValueError:
            logger.warning("No chains in the atom array. Returning None for motif.")
            logger.warning(
                f"Got the following unique asym_ids: {np.unique(atom_array.label_asym_id)}"
            )
            return None

        chain_array = atom_array[atom_array.label_asym_id == chain_id]

        # Pocket heuristic
        pocket_scores = compute_pocket_scores(
            chain_array, n_neighbors=self.pocket_n_neighbours
        )
        pocket_atoms = chain_array[(pocket_scores <= self.pocket_score_threshold)]
        if len(pocket_atoms) == 0:
            logger.warning("No pocket atoms found. Returning None for motif.")
            return None

        # Generate motif
        motif_array = self._generate_motif_around_point(
            point_coord=get_seed_atom_from_array(pocket_atoms),
            atom_array=chain_array,
        )

        return motif_array

    def _generate_motif_around_point(
        self,
        point_coord: np.array,
        atom_array: AtomArray,
    ) -> AtomArray:
        """
        Generates a motif around a point by identifying which residues
        lie in a nearby sphere (radius picked from a uniform distribution). Then, iterates over the
        residues, generating some both tip-atom residues and all-atom residues (proportion
        decided by `whole_sidechain_probability`).

        Args:
            point_coord (np.array): The centre point round which we generate our motif.
            atom_array (AtomArray): The AtomArray which we generate our motif from.

        Returns:
            AtomArray: Motif atom array around the specified point
        """
        motif_array = AtomArray(0)

        # Pick a radius uniformly between radius_min and radius_max
        r = np.random.uniform(self.r_min, self.r_max)

        # Calculate distances from seed atom to all atoms in the full array
        distances = np.linalg.norm(atom_array.coord - point_coord, axis=-1)

        # Find atoms within radius
        within_radius_mask = distances <= r
        atoms_in_sphere = atom_array[within_radius_mask]

        # Identify unique polymer residues within the sphere
        polymer_mask = np.isin(
            atoms_in_sphere.chain_mol_type, ["protein", "RNA", "DNA"]
        )
        polymer_atoms_in_sphere = atoms_in_sphere[polymer_mask]

        if len(polymer_atoms_in_sphere) == 0:
            logger.warning(
                "No polymer atoms close to ligand. Returning None for motif."
            )
            return motif_array

        unique_ref_space_uids_in_sphere = np.unique(
            polymer_atoms_in_sphere.ref_space_uid
        )
        motif_residues = []

        for uid in unique_ref_space_uids_in_sphere:
            residue = atom_array[atom_array.ref_space_uid == uid]
            motif_residues.append(residue)

        # Add residues in sphere to motif
        if len(motif_residues) == 0:
            logger.warning("No residues in sphere. Returning None for motif.")
            return None

        for residue in motif_residues:
            if np.random.rand() > self.residue_inclusion_prob:
                # Skip residue
                continue
            if np.random.rand() > self.whole_sidechain_prob:
                # Only partial residue to motif
                motif_array += self._get_partial_residue_motif(residue)
            else:
                # All residue atoms added to motif
                motif_array += residue

        return motif_array

    def _get_partial_residue_motif(self, residue_atom_array: AtomArray) -> AtomArray:
        """
        Get tip atoms like in RFdiff2. We pick a seed atom on the residue (80% of
        the time this is the tip, remaining 20% we pick at random) and then extend
        outward by n_bonds ~ Geo(p).

        Args:
            residue_atom_array (AtomArray): AtomArray containing a single residue

        Returns:
            AtomArray: Partial residue motif atom array
        """
        G_res = residue_atom_array.bonds.as_graph()

        if np.random.rand() < self.sidechain_seed_is_tip_prob:
            # seed is tip atom
            tip_atom_id = len(residue_atom_array) - 1
        else:
            # seed is picked uniformly at random
            tip_atom_id = np.random.choice(len(residue_atom_array))

        # number of bonds to extend out from seed picked with geo(p)
        num_bonds = np.random.geometric(self.sidechain_bfs_depth_prob) - 1

        # get atoms within num_bonds of seed atom
        motif_atom_ids = nx.single_source_shortest_path_length(
            G_res, tip_atom_id, cutoff=num_bonds
        )
        motif_atom_ids = list(motif_atom_ids.keys())

        return residue_atom_array[motif_atom_ids]

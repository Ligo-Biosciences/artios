"""Motif-CIF parse parity against locked AtomArray snapshots.

The motif-CIF path is exercised during inference via
``Motif.from_spec(cif_file=...)`` → ``MmcifReader.atom_array()`` — the
lightweight parse (no bioassembly expansion, no annotation pipeline),
distinct from ``load_bioassembly``. The refactor must preserve this path
byte-for-byte so every downstream inference test
(``test_backbone_input_smiles_ligand.py``, ``test_array_builder.py``,
``test_infer_parity.py::TestMotifDataset``) stays valid.

Snapshots live under ``tests/fixtures/motif_cif/<domain>/<stem>.npz`` and
are regenerated by ``tests/fixtures/motif_cif/regenerate.py``.

This test parametrises over every motif CIF in
``evaluation/inputs/motifs/`` — the AME benchmark plus the luciferase,
esterase and cutinase campaigns — so the refactor's blast
radius on inference is pinned end-to-end for the actual JSON inputs
shipped with the evaluation runner.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from artios.data.parsing.mmcif import MmcifReader
from artios.utils.file_io import load_atomarray_from_npz
from tests._helpers.structure_equality import assert_atom_arrays_equal

REPO_ROOT = Path(__file__).resolve().parents[2]
MOTIF_CIF_DIR = REPO_ROOT / "evaluation" / "inputs" / "motifs"
SNAPSHOT_DIR = REPO_ROOT / "tests" / "fixtures" / "motif_cif"


def _enumerate_cases() -> list[pytest.param]:
    """One ``pytest.param`` per motif CIF, with a stable id."""
    if not MOTIF_CIF_DIR.exists():
        return []
    cases: list[pytest.param] = []
    for cif_path in sorted(MOTIF_CIF_DIR.rglob("*.cif")):
        rel = cif_path.relative_to(MOTIF_CIF_DIR)
        # "<domain>/<stem>" — avoids collisions across domains.
        case_id = str(rel.with_suffix("")).replace("/", "__")
        cases.append(pytest.param(cif_path, rel, id=case_id))
    return cases


MOTIF_CIF_CASES = _enumerate_cases()


# Allowlist for motif-CIF parity — same semantics as
# ``test_cif_parse_parity.PARITY_ALLOWLIST``. Keyed by
# ``"<domain>/<stem>:<field>"`` so a single file's mismatch can be
# allowlisted without spilling to siblings.
MOTIF_PARITY_ALLOWLIST: dict[str, str] = {}


@pytest.mark.skipif(
    not MOTIF_CIF_CASES,
    reason=(
        f"no motif CIFs under {MOTIF_CIF_DIR.relative_to(REPO_ROOT)}; "
        "evaluation assets not checked out?"
    ),
)
@pytest.mark.parametrize("cif_path,rel_path", MOTIF_CIF_CASES)
def test_motif_cif_parse_matches_snapshot(
    cif_path: Path,
    rel_path: Path,
) -> None:
    """``MmcifReader(path).atom_array()`` for every motif CIF must
    match the committed snapshot under ``tests/fixtures/motif_cif/``."""
    snapshot_path = SNAPSHOT_DIR / rel_path.with_suffix(".npz")
    if not snapshot_path.exists():
        pytest.skip(
            f"motif-CIF snapshot missing: {snapshot_path}. "
            "Run `uv run python -m tests.fixtures.motif_cif.regenerate`."
        )

    actual = MmcifReader(cif_path).atom_array()
    expected = load_atomarray_from_npz(snapshot_path)

    # Per-file allowlist keys: "<id>:<field>". Build a filtered view.
    case_id = str(rel_path.with_suffix("")).replace("/", "__")
    per_case_allowlist = {
        k.split(":", 1)[1]: v
        for k, v in MOTIF_PARITY_ALLOWLIST.items()
        if k.startswith(f"{case_id}:")
    }
    # "*" wildcard entries apply to every case.
    per_case_allowlist.update(
        {
            k.split(":", 1)[1]: v
            for k, v in MOTIF_PARITY_ALLOWLIST.items()
            if k.startswith("*:")
        }
    )

    assert_atom_arrays_equal(actual, expected, allowlist=per_case_allowlist)


def test_every_motif_cif_has_a_snapshot() -> None:
    """Invariant: every motif CIF under ``evaluation/inputs/motifs/`` has
    a committed snapshot. Catches the drift where a new motif fixture is
    added to evaluation/ but no one runs the regenerate script.
    """
    if not MOTIF_CIF_DIR.exists():
        pytest.skip("evaluation motifs directory not present")
    missing: list[Path] = []
    for cif_path in sorted(MOTIF_CIF_DIR.rglob("*.cif")):
        rel = cif_path.relative_to(MOTIF_CIF_DIR)
        snap = SNAPSHOT_DIR / rel.with_suffix(".npz")
        if not snap.exists():
            missing.append(rel)
    if missing:
        listing = "\n  - ".join(str(p) for p in missing)
        pytest.fail(
            f"{len(missing)} motif CIF(s) have no parity snapshot. "
            f"Run `uv run python -m tests.fixtures.motif_cif.regenerate`:\n  - {listing}"
        )
